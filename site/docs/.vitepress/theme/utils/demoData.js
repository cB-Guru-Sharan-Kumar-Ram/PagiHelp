// In-browser evaluator: reproduces the query semantics over the demo rows.

function likeToRegex(pattern, caseInsensitive) {
  let out = "^";
  for (const ch of String(pattern)) {
    if (ch === "%") out += ".*";
    else if (ch === "_") out += ".";
    else out += ch.replace(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);
  }
  out += "$";
  return new RegExp(out, caseInsensitive ? "i" : "");
}

function compare(a, b) {
  if (typeof a === "number" && typeof b === "number") return a - b;
  const sa = String(a);
  const sb = String(b);
  if (sa < sb) return -1;
  return sa > sb ? 1 : 0;
}

function matchFilter(row, [field, op, value]) {
  const v = row[field];
  switch (String(op).toUpperCase()) {
    case "=":
      return v == value;
    case "!=":
    case "<>":
      return v != value;
    case ">":
      return compare(v, value) > 0;
    case ">=":
      return compare(v, value) >= 0;
    case "<":
      return compare(v, value) < 0;
    case "<=":
      return compare(v, value) <= 0;
    case "IN":
      return Array.isArray(value) && value.some((x) => x == v);
    case "NOT IN":
      return Array.isArray(value) && !value.some((x) => x == v);
    case "LIKE":
      return likeToRegex(value, false).test(String(v));
    case "ILIKE":
      return likeToRegex(value, true).test(String(v));
    default:
      return true;
  }
}

// Operators the evaluator can reproduce; anything else still builds correct SQL but skips the row preview.
const EVALUABLE_OPS = new Set([
  "=", "!=", "<>", ">", ">=", "<", "<=", "IN", "NOT IN", "LIKE", "ILIKE",
]);

function isConditionTuple(node) {
  return (
    Array.isArray(node) &&
    node.length === 3 &&
    typeof node[0] === "string" &&
    typeof node[1] === "string"
  );
}

// Evaluate the filter tree (even depth = AND, odd = OR); throws `.unsupportedOp` if an op can't be evaluated.
function evalFilterNode(node, row, depth) {
  if (isConditionTuple(node)) {
    const op = String(node[1]).toUpperCase();
    if (!EVALUABLE_OPS.has(op)) {
      const err = new Error("unsupported operator");
      err.unsupportedOp = node[1];
      throw err;
    }
    return matchFilter(row, node);
  }
  if (!Array.isArray(node)) return true;
  const results = node.map((child) => evalFilterNode(child, row, depth + 1));
  return depth % 2 === 0 ? results.every(Boolean) : results.some(Boolean);
}

// Which columns search applies to; `complex` flags statement/prefixed columns the evaluator can't model.
function searchColumnsFor(opt, table) {
  if (!Array.isArray(opt.searchColumnList)) {
    return { cols: table.searchColumns, complex: false };
  }
  const complex = opt.searchColumnList.some((c) => c?.statement || c?.prefix);
  const cols = opt.searchColumnList
    .filter((c) => c?.name && !c.prefix && !c.statement)
    .map((c) => c.name);
  return { cols, complex };
}

// AND-ed additionalWhereConditions, then free-text search, then the request filters.
function applyFilters(rows, request, searchCols, awc) {
  let out = rows;
  if (awc?.length) out = out.filter((r) => evalFilterNode(awc, r, 0));
  if (request.search) {
    const term = String(request.search).toLowerCase();
    out = out.filter((r) =>
      searchCols.some((c) => String(r[c]).toLowerCase().includes(term))
    );
  }
  if (request.filters?.length) {
    out = out.filter((r) => evalFilterNode(request.filters, r, 0));
  }
  return out;
}

function sortRows(rows, sort) {
  if (!sort?.attributes?.length) return rows;
  return rows.sort((a, b) => {
    for (let i = 0; i < sort.attributes.length; i += 1) {
      const dir = String(sort.sorts[i]).toUpperCase() === "DESC" ? -1 : 1;
      const c = compare(a[sort.attributes[i]], b[sort.attributes[i]]);
      if (c !== 0) return c * dir;
    }
    return 0;
  });
}

function paginateRows(rows, request) {
  let offset = 0;
  let limit = rows.length;
  if (request.pageNo !== undefined && request.itemsPerPage !== undefined) {
    offset = (request.pageNo - 1) * request.itemsPerPage;
    limit = request.itemsPerPage;
  } else if (request.offset !== undefined && request.limit !== undefined) {
    offset = request.offset;
    limit = request.limit;
  }
  return rows.slice(offset, offset + limit);
}

// Run a request over the demo rows, honoring the options block; returns { computable, rows, total, reason? }.
export function runRequest(tableKey, request, options) {
  const table = TABLES[tableKey];
  try {
    const opt = (Array.isArray(options) && options[0]) || {};

    if (opt.joinQuery && String(opt.joinQuery).trim()) {
      return {
        computable: false,
        reason: "a custom joinQuery (joins aren’t modelled in the browser)",
        rows: [],
        total: 0,
      };
    }

    const { cols: searchCols, complex } = searchColumnsFor(opt, table);
    if (complex && request.search) {
      return {
        computable: false,
        reason: "a statement/prefixed search column",
        rows: [],
        total: 0,
      };
    }

    const filtered = applyFilters(
      table.rows.slice(),
      request,
      searchCols,
      opt.additionalWhereConditions
    );
    const sorted = sortRows(filtered, request.sort);
    return {
      computable: true,
      rows: paginateRows(sorted, request),
      total: sorted.length,
    };
  } catch (e) {
    return {
      computable: false,
      reason: e?.unsupportedOp
        ? `the “${e.unsupportedOp}” operator`
        : "this request shape",
      rows: [],
      total: 0,
    };
  }
}
